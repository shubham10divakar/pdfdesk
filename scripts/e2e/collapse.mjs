// Collapsible sidebar / notes panel: widths, keys, persistence, floating reopen button.
import { writeFileSync } from "node:fs";
const [port, app, pdf, out] = process.argv.slice(2);
const wait = ms => new Promise(r => setTimeout(r, ms));
let fails = 0; const check = (ok, what) => { console.log(ok ? "PASS" : "FAIL", what); if (!ok) fails++; };
const list = await (await fetch(`http://127.0.0.1:${port}/json/list`)).json();
const ws = new WebSocket(list.find(t => t.type === "page").webSocketDebuggerUrl);
await new Promise(r => ws.addEventListener("open", r, { once: true }));
let id = 0; const pend = new Map();
ws.addEventListener("message", e => { const m = JSON.parse(e.data); if (pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } });
const cdp = (method, params = {}) => new Promise((res, rej) => { const i = ++id; pend.set(i, m => m.error ? rej(new Error(m.error.message)) : res(m.result)); ws.send(JSON.stringify({ id: i, method, params })); });
const js = async e => { const r = await cdp("Runtime.evaluate", { expression: e, awaitPromise: true, returnByValue: true }); if (r.exceptionDetails) throw new Error(r.exceptionDetails.exception?.description || e); return r.result.value; };
const key = k => js(`document.body.dispatchEvent(new KeyboardEvent("keydown", {key:${JSON.stringify(k)}, bubbles:true}))`);
const shot = async n => writeFileSync(`${out}/${n}.png`, Buffer.from((await cdp("Page.captureScreenshot", { format: "png" })).data, "base64"));
const pageW = () => js(`document.querySelector('#pages .page').getBoundingClientRect().width`);
const vis = sel => js(`(() => { const e = document.querySelector(${JSON.stringify(sel)}); return !!e && getComputedStyle(e).display !== "none" && !e.hidden; })()`);
await cdp("Page.enable"); await cdp("Runtime.enable"); await cdp("DOM.enable");
await cdp("Emulation.setDeviceMetricsOverride", { width: 1100, height: 800, deviceScaleFactor: 1, mobile: false });
await cdp("Page.navigate", { url: app }); await wait(1800);
const { root } = await cdp("DOM.getDocument"); const { nodeId } = await cdp("DOM.querySelector", { nodeId: root.nodeId, selector: "#fileIn" });
await cdp("DOM.setFileInputFiles", { nodeId, files: [pdf] }); await wait(2500);
await js(`[...document.querySelectorAll('[data-act="open"]')].find(e => /Reading Logs/.test(e.textContent)).click()`); await wait(2500);
await js(`document.querySelector('#pages').scrollTop = document.querySelectorAll('#pages .page')[1].offsetTop`); await wait(600);
const pg = await js(`document.querySelector('#pgIn').value`);
const w0 = await pageW();
await key("]"); await wait(900);
const w1 = await pageW();
check(!(await vis(".r-panel")) && w1 > w0, `] hides the notes panel and the page gets wider (${Math.round(w0)} -> ${Math.round(w1)}px)`);
await key("["); await wait(900);
const w2 = await pageW();
check(!(await vis(".side")) && w2 > w1, `[ hides the sidebar and the page gets wider again (${Math.round(w2)}px)`);
check(await js(`document.querySelector('#pgIn').value`) === pg, `still on page ${pg} after re-fitting`);
check(!(await vis("#sideOpen")), "in the reader the toolbar's own button is used, no floating button");
await shot("collapse-both");
await cdp("Page.reload"); await wait(1800);
await js(`[...document.querySelectorAll('[data-act="open"]')].find(e => /Reading Logs/.test(e.textContent)).click()`); await wait(2000);
check(!(await vis(".side")) && !(await vis(".r-panel")), "both stay hidden after a reload");
await js(`document.querySelector('[data-act="home"]').click()`); await wait(500);
check(await vis("#sideOpen"), "outside the reader a floating button offers the sidebar back");
await shot("collapse-home");
await js(`document.querySelector('#sideOpen').click()`); await wait(400);
check(await vis(".side") && !(await vis("#sideOpen")), "the floating button brings the sidebar back");
await js(`(() => { const q = document.querySelector('#q'); q.focus(); q.dispatchEvent(new KeyboardEvent("keydown", {key:"[", bubbles:true})); })()`); await wait(300);
check(await vis(".side"), "typing [ in the search box doesn't hide the sidebar");
await js(`[...document.querySelectorAll('[data-act="open"]')].find(e => /Reading Logs/.test(e.textContent)).click()`); await wait(1800);
await js(`document.querySelector('.tg-panel').click()`); await wait(700);
check(await vis(".r-panel"), "the toolbar button shows the notes panel again");
await shot("collapse-none");
console.log(fails ? `\n${fails} FAILED` : "\nALL PASSED");
ws.close(); process.exit(fails ? 1 : 0);
